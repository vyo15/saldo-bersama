const definePolicy = (mode, { maintenanceAllowed = false, idempotencyRequired = false, retryUnknownSafe = false, snapshot = false } = {}) => Object.freeze({
  mode,
  maintenanceAllowed,
  idempotencyRequired,
  retryUnknownSafe,
  snapshot: mode === "read" && Boolean(snapshot),
});

const read = (options) => definePolicy("read", options);
const snapshotRead = (options = {}) => read({ ...options, snapshot: true });
const write = (options = {}) => definePolicy("write", { idempotencyRequired: true, ...options });
const external = (options = {}) => definePolicy("external", { idempotencyRequired: true, ...options });

